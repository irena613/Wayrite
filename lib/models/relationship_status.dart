/// Статус на врска помеѓу тековниот корисник и друг корисник.
/// Се користи во екранот за пребарување за да се одлучи кое копче да се прикаже.
enum RelationshipStatus {
  none, // нема врска -> копче "Додај"
  requestSent, // јас сум испратил барање -> "Чека одговор"
  requestReceived, // тој ми испратил барање -> "Прифати" / "Одбиј"
  friends, // веќе пријатели -> "Пријатели"
}
